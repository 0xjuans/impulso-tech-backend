package tech.impulso.gamification.entity;

/**
 * Categorías temáticas de las insignias otorgables por Impulso Tech.
 */
public enum BadgeCategory {

    /** Reconoce el avance del estudiante en el consumo de contenido. */
    PROGRESO,

    /** Reconoce logros vinculados al sistema de gamificación (XP, racha, nivel). */
    GAMIFICACION,

    /**
     * Insignias otorgadas manualmente o mediante campañas puntuales
     * (eventos, aniversarios, colaboraciones).
     */
    ESPECIAL
}
