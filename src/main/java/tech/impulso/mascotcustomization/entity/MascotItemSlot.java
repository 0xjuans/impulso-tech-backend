package tech.impulso.mascotcustomization.entity;

/**
 * Ranura visual de la mascota en la que se aplica un ítem
 * desbloqueable (RF-052).
 */
public enum MascotItemSlot {

    /** Aspecto general o color de la piel. */
    SKIN,

    /** Prenda que se equipa en la cabeza. */
    HAT,

    /** Accesorio que se equipa sobre el cuerpo o alrededor. */
    ACCESSORY,

    /** Fondo o escenario detrás de la mascota. */
    BACKGROUND
}
